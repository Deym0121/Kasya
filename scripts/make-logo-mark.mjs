/**
 * Generates the transparent Kasya "K" runner mark from the app icon:
 *   assets/art/kasya-mark.png      (512 px tall, orange K on transparent — in-app headers)
 *   src/share/brandAssets.ts       (small base64 PNGs embedded in share-image SVGs)
 *
 * The icon is an orange K on near-black. Each pixel's alpha comes from how far
 * its red channel sits above the background, and the colour is un-premultiplied
 * against that background, so antialiased edges stay smooth on any backdrop.
 * Re-run after changing assets/icon.png:  node scripts/make-logo-mark.mjs
 */
import Jimp from 'jimp-compact';
import { writeFileSync } from 'node:fs';

const BG = [14, 14, 14];
const src = await Jimp.read('assets/icon.png');
const { width: W, height: H } = src.bitmap;
const out = new Jimp(W, H, 0x00000000);
let minX = W, minY = H, maxX = 0, maxY = 0;
src.scan(0, 0, W, H, function (x, y, i) {
  const [r, g, b] = [this.bitmap.data[i], this.bitmap.data[i + 1], this.bitmap.data[i + 2]];
  const a = Math.max(0, Math.min(1, (r - BG[0] - 8) / (240 - BG[0] - 8)));
  if (a <= 0) return;
  const un = (c, k) => Math.max(0, Math.min(255, Math.round((c - (1 - a) * BG[k]) / a)));
  const j = (y * W + x) * 4;
  out.bitmap.data[j] = un(r, 0);
  out.bitmap.data[j + 1] = un(g, 1);
  out.bitmap.data[j + 2] = un(b, 2);
  out.bitmap.data[j + 3] = Math.round(a * 255);
  if (a > 0.1) {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
});
const pad = 12;
out.crop(Math.max(0, minX - pad), Math.max(0, minY - pad), Math.min(W, maxX - minX + 2 * pad), Math.min(H, maxY - minY + 2 * pad));
const mark = out.clone().resize(Jimp.AUTO, 512);
await mark.writeAsync('assets/art/kasya-mark.png');

const small = await out.clone().resize(Jimp.AUTO, 160).getBase64Async(Jimp.MIME_PNG);
const appIcon = await (await Jimp.read('assets/splash-icon.png')).resize(160, 160).getBase64Async(Jimp.MIME_PNG);
const ratio = mark.bitmap.width / mark.bitmap.height;
writeFileSync(
  'src/share/brandAssets.ts',
  `// GENERATED by scripts/make-logo-mark.mjs — do not edit by hand.\n` +
    `/** The orange K runner mark on transparent, as a PNG data URI (160 px tall). */\n` +
    `export const MARK_PNG = '${small}';\n` +
    `/** width / height of the mark */\n` +
    `export const MARK_RATIO = ${ratio.toFixed(4)};\n` +
    `/** The rounded-square app icon (transparent corners), PNG data URI, 160 px. */\n` +
    `export const APP_ICON_PNG = '${appIcon}';\n`,
);
console.log('mark', mark.bitmap.width, 'x', mark.bitmap.height, 'ratio', ratio.toFixed(3), 'b64 bytes', small.length, appIcon.length);
