/**
 * Best guess at the runner's country from the device time zone, then the
 * locale's region ('en-PH'), else the Philippines.
 */
export function guessCountry(timeZone?: string | null, locale?: string | null): string {
  const z = timeZone ? ZONE_COUNTRY[timeZone] : undefined;
  if (z) return z;
  const region = locale?.match(/[-_]([A-Z]{2})\b/)?.[1];
  if (region && isCountryCode(region)) return region;
  return HOME_COUNTRY;
}
