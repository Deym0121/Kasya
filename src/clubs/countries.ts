const BY_CODE = new Map(COUNTRIES.map(([c, n]) => [c, n]));

/** Kasya's home market — the default club country and country leaderboard. */
export const HOME_COUNTRY = 'PH';

export function isCountryCode(code: unknown): code is string {
  return typeof code === 'string' && BY_CODE.has(code);
}

export function countryName(code: string): string {
  return BY_CODE.get(code) ?? code;
}

/** 'PH' → 🇵🇭 (regional indicator symbols). */
export function flagEmoji(code: string): string {
  if (!/^[A-Z]{2}$/.test(code)) return '🏳️';
  return String.fromCodePoint(...[...code].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65));
}

